/**
 * Golden snapshot harness. In check mode (the default, and in CI) every case's output must
 * match its committed `test/golden/<name>.json` byte for byte, no snapshot may be missing or
 * orphaned, and `golden-summary.md` must be current. `pnpm golden:update` (GOLDEN_UPDATE=1)
 * rewrites all of them; the PR description must then explain why the outputs changed.
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { goldenCases } from "./golden-cases.ts";

const GOLDEN_DIR = join(import.meta.dirname, "golden");
const SUMMARY_FILE = join(GOLDEN_DIR, "golden-summary.md");
const UPDATE = process.env["GOLDEN_UPDATE"] === "1";
const HINT = "Run `pnpm golden:update` and explain the change in the PR description.";

const results = await Promise.all(goldenCases.map(async (c) => ({ ...c, ...(await c.compute()) })));

function serialize(output: unknown): string {
  return `${JSON.stringify(output, null, 2)}\n`;
}

function renderSummary(): string {
  const lines = [
    "# Golden summary",
    "",
    "Generated by `pnpm golden:update` from `test/golden/*.json`. Do not edit by hand.",
    "",
  ];
  for (const r of results) {
    lines.push(`## ${r.name}`, "", r.description, "");
    for (const [key, value] of Object.entries(r.summary)) lines.push(`- ${key}: ${value}`);
    lines.push("");
  }
  return lines.join("\n");
}

if (UPDATE) {
  mkdirSync(GOLDEN_DIR, { recursive: true });
  const names = new Set(results.map((r) => `${r.name}.json`));
  for (const file of readdirSync(GOLDEN_DIR)) {
    if (file.endsWith(".json") && !names.has(file)) rmSync(join(GOLDEN_DIR, file));
  }
  for (const r of results) writeFileSync(join(GOLDEN_DIR, `${r.name}.json`), serialize(r.output));
  writeFileSync(SUMMARY_FILE, renderSummary());
}

describe("golden snapshots", () => {
  it("has unique case names", () => {
    expect(new Set(results.map((r) => r.name)).size).toBe(results.length);
  });

  it.each(results.map((r) => [r.name, r] as const))("%s matches its snapshot", (name, r) => {
    const file = join(GOLDEN_DIR, `${name}.json`);
    expect(existsSync(file), `Missing snapshot ${file}. ${HINT}`).toBe(true);
    expect(serialize(r.output), `Stale snapshot ${file}. ${HINT}`).toBe(readFileSync(file, "utf8"));
  });

  it("has no orphaned snapshots", () => {
    const names = new Set(results.map((r) => `${r.name}.json`));
    const orphans = readdirSync(GOLDEN_DIR).filter((f) => f.endsWith(".json") && !names.has(f));
    expect(orphans, `Orphaned snapshots. ${HINT}`).toEqual([]);
  });

  it("has a current golden-summary.md", () => {
    expect(existsSync(SUMMARY_FILE), `Missing ${SUMMARY_FILE}. ${HINT}`).toBe(true);
    expect(renderSummary(), `Stale golden-summary.md. ${HINT}`).toBe(readFileSync(SUMMARY_FILE, "utf8"));
  });
});
